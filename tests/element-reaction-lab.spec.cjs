const {test,expect}=require('@playwright/test');
test('ELEMENT lab matrix, replay, scan, export and sandbox transfer',async({page})=>{
 test.setTimeout(120000);
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:4173/games/element/index.html');
 await page.locator('#rlOpen').click();
 await expect(page.locator('#reactionLab')).toBeVisible();
 const materialCount=await page.locator('#rlA option').count();
 const total=materialCount*materialCount;
 await expect(page.locator('#rlMatrix .rlCell')).toHaveCount(total);
 await page.locator('#rlPair').click();
 await expect(page.locator('#rlDetail')).toContainText('Doğrudan dönüşüm');
 await expect(page.locator('#rlDetail')).toContainText('Tuzlu su');
 await page.locator('#rlFrame').fill('0');
 await expect(page.locator('#rlFrameLabel')).toContainText('Adım 0');
 await page.locator('#rlSteps').selectOption('8');
 await page.locator('#rlTrials').selectOption('1');
 await page.locator('#rlRun').click();
 await expect(page.locator('#rlRunState')).toHaveText('Tarama tamamlandı.',{timeout:100000});
 await expect(page.locator('#rlSummary')).toContainText(total+' / '+total);
 const dl=page.waitForEvent('download');await page.locator('#rlCsv').click();expect((await dl).suggestedFilename()).toBe('element-reactions.csv');
 await page.locator('#rlPair').click();await page.locator('#rlOpenWorld').click();
 await expect(page.locator('#reactionLab')).not.toBeVisible();
 await expect(page.locator('#pause')).toContainText('Başlat');
 await expect(page.locator('#info')).toContainText('Deney başlangıcı');
 await page.locator('#undo').click();
 expect(errors).toEqual([]);
});
